function buildPrograms(
  directionRoute: string,
  childIds?: string[],
): DirectionPageData["programs"]["cards"] {
  const base = [
    { id: "bazova", title: "Базова", shortDescription: "Базова програма для поступового відновлення рухливості, сили та самоконтролю.", price: "Уточнюйте", duration: "4–6 занять" },
    { id: "standartna", title: "Стандартна", shortDescription: "Розширений план з більш регулярним контролем навантящення та динаміки стану.", price: "Уточнюйте", duration: "6–8 занять" },
    { id: "rozshyrena", title: "Розширена", shortDescription: "Комплексна програма з повним обсягом навантящення, контролю та рекомендацій для відновлення.", price: "Уточнюйте", duration: "8–12 занять" },
    { id: "indyvidualna", title: "Індивідуальна", shortDescription: "Індивідуальний маршрут з адаптацією до особливостей пацієнта і темпу відновлення.", price: "Уточнюйте", duration: "за індивідуальним планом", format: "амбулаторно / виїзно" },
  ];
  return base.map((p, i) => ({
    id: p.id,
    title: p.title,
    shortDescription: p.shortDescription,
    duration: p.duration,
    priceLabel: p.price,
    route: childIds?.[i] ?? directionRoute,
    isPopular: p.id === "standartna",
  }));
}

